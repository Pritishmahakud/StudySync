import { NextRequest, NextResponse } from 'next/server'
import { getApiSession } from '@/lib/api-auth'
import { getUserDocuments, saveUserDocument, deleteUserDocument } from '@/lib/user-learning-store'

export async function GET() {
  const { user, errorResponse } = await getApiSession()
  if (errorResponse) return errorResponse

  const docs = getUserDocuments(user.id, user.email)
  return NextResponse.json({
    status: 'success',
    documents: docs
  })
}

export async function POST(req: NextRequest) {
  const { user, errorResponse } = await getApiSession()
  if (errorResponse) return errorResponse

  try {
    const body = await req.json()
    if (!body.title && !body.fileName) {
      return NextResponse.json({ status: 'error', message: 'Document title or fileName is required.' }, { status: 400 })
    }

    const saved = saveUserDocument(user.id, user.email, {
      fileName: body.fileName || 'document.pdf',
      title: body.title || body.fileName || 'Academic Document',
      summary: body.summary || 'Summary generated by Document AI.',
      domain: body.domain || 'Computer Science',
      keyTakeaways: body.keyTakeaways || [],
      modules: body.modules || [],
      quiz: body.quiz || [],
      flashcards: body.flashcards || []
    })

    return NextResponse.json({
      status: 'success',
      document: saved
    })
  } catch (error: any) {
    return NextResponse.json({ status: 'error', message: error.message }, { status: 500 })
  }
}

export async function DELETE(req: NextRequest) {
  const { user, errorResponse } = await getApiSession()
  if (errorResponse) return errorResponse

  try {
    const { searchParams } = new URL(req.url)
    const id = searchParams.get('id') || ''
    if (!id) {
      return NextResponse.json({ status: 'error', message: 'Document id is required.' }, { status: 400 })
    }

    const deleted = deleteUserDocument(user.id, user.email, id)
    return NextResponse.json({ status: 'success', deleted })
  } catch (error: any) {
    return NextResponse.json({ status: 'error', message: error.message }, { status: 500 })
  }
}
